def build_document():
    doc = Document()

    # ── 页面设置：紧凑 ──
    section = doc.sections[0]
    section.page_width = Cm(21)
    section.page_height = Cm(29.7)
    section.left_margin = Cm(1.8)
    section.right_margin = Cm(1.8)
    section.top_margin = Cm(1.5)
    section.bottom_margin = Cm(1.5)

    # ── 正文样式：紧凑 ──
    style = doc.styles["Normal"]
    style.font.name = "微软雅黑"
    style.font.size = Pt(10)
    style.paragraph_format.line_spacing = 1.25
    style.paragraph_format.space_after = Pt(2)
    style.paragraph_format.space_before = Pt(0)
    rPr = style.element.get_or_add_rPr()
    rFonts = rPr.makeelement(qn('w:rFonts'), {})
    rFonts.set(qn('w:eastAsia'), '微软雅黑')
    rPr.insert(0, rFonts)

    # ── 设置 Heading 样式 ──
    for i in [1, 2, 3]:
        h_style = doc.styles[f"Heading {i}"]
        h_style.font.name = "微软雅黑"
        h_style.font.color.rgb = RGBColor(0, 0, 0)
        h_rPr = h_style.element.get_or_add_rPr()
        h_rFonts = h_rPr.makeelement(qn('w:rFonts'), {})
        h_rFonts.set(qn('w:eastAsia'), '微软雅黑')
        h_rPr.insert(0, h_rFonts)

    doc.styles["Heading 1"].font.size = Pt(14)
    doc.styles["Heading 1"].paragraph_format.space_before = Pt(12)
    doc.styles["Heading 1"].paragraph_format.space_after = Pt(4)
    doc.styles["Heading 1"].paragraph_format.line_spacing = 1.2

    doc.styles["Heading 2"].font.size = Pt(11.5)
    doc.styles["Heading 2"].paragraph_format.space_before = Pt(8)
    doc.styles["Heading 2"].paragraph_format.space_after = Pt(2)
    doc.styles["Heading 2"].paragraph_format.line_spacing = 1.2

    doc.styles["Heading 3"].font.size = Pt(10.5)
    doc.styles["Heading 3"].paragraph_format.space_before = Pt(6)
    doc.styles["Heading 3"].paragraph_format.space_after = Pt(2)

    # ── 封面 ──
    p_title = doc.add_paragraph()
    p_title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_title.paragraph_format.space_before = Pt(40)
    run = p_title.add_run("品牌管理课程笔记")
    run.font.size = Pt(22)
    run.font.bold = True
    run.font.name = "微软雅黑"

    p_sub = doc.add_paragraph()
    p_sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run2 = p_sub.add_run("基于课堂PPT整理 · 纯中文精修版 · 2026")
    run2.font.size = Pt(10)
    run2.font.color.rgb = RGBColor(128, 128, 128)

    doc.add_paragraph()  # spacer

    # ── 写入内容 ──
    for chapter_title, sections in NOTES:
        doc.add_heading(chapter_title, level=1)

        for section_title, content in sections:
            if section_title:
                doc.add_heading(section_title, level=2)
            # 将内容按 \n 拆分，每条作为要点段落
            lines = content.strip().split('\n')
            for line in lines:
                line = line.strip()
                if not line:
                    continue
                p = doc.add_paragraph(line)
                # 如果以数字或"案例"开头，缩进
                if line and (line[0] in '①②③④⑤⑥⑦⑧⑨⑩' or line.startswith('案例') or line.startswith('Step')):
                    p.paragraph_format.left_indent = Cm(0.5)

    # ── 页尾说明 ──
