def apply_ocr_fixes(text: str) -> str:
    """应用 OCR 纠错词典"""
    result = text
    for wrong, correct in OCR_FIXES:
        if wrong in result:
            result = result.replace(wrong, correct)
    for wrong, correct in FINAL_FIXES:
        if wrong in result:
            result = result.replace(wrong, correct)
    return result


def is_chinese_line(text: str) -> bool:
    """判断是否为中文行（中文占比 > 30%）"""
    if not text.strip():
        return False
    cn = sum(1 for c in text if '一' <= c <= '鿿' or '㐀' <= c <= '䶿')
    total = len(text.replace(' ', '').replace('\n', ''))
    return cn > 0 and cn / max(total, 1) > 0.3


def is_english_line(text: str) -> bool:
    """判断是否为英文行"""
    stripped = text.strip()
    if not stripped:
        return False
    alpha = sum(1 for c in stripped if c.isascii() and c.isalpha())
    total = len(stripped.replace(' ', ''))
    return alpha > 0 and alpha / max(total, 1) > 0.5


def is_noise(text: str) -> bool:
    """判断是否为噪音行"""
    stripped = text.strip()
    if not stripped:
        return True
    # 页码
    if re.match(r'^(of|\d+)\s*$', stripped):
        return True
    if re.match(r'^\d+\s*$', stripped) and len(stripped) <= 5:
        return True
    # 单个字母或符号
    if re.match(r'^[A-Za-z•\-•◆\*]$', stripped):
        return True
    # 纯数字+符号组合（如 "9 6"）
    if re.match(r'^[\d\s]+$', stripped):
        return True
    # 单字噪音
    if len(stripped) <= 1 and '一' <= stripped <= '鿿':
        return True
    # 纯特殊字符
    if not any(c.isalnum() or '一' <= c <= '鿿' for c in stripped):
        return True
    return False


def is_heading_like(text: str) -> bool:
    """判断是否为标题行"""
    stripped = text.strip()
    # 数字编号开头
    if re.match(r'^[一二三四五六七八九十\d]+[、.．）)]', stripped):
        return True
    # "第X章/节/讲"
    if re.match(r'^第[一二三四五六七八九十\d]+[章节讲课]', stripped):
        return True
    # 以"品牌"开头且较短
    if stripped.startswith('品牌') and len(stripped) <= 25:
        return True
    # 结尾含"是什么/定义/策略/原则/步骤"等标识词
    if re.search(r'(是什么|定义|策略|原则|步骤|构成|模型|概述|区别|联系)$', stripped):
        return True
    return False


def extract_cn_content(paragraphs: list) -> list:
    """
    从段落列表提取中文内容，同时保存英文作为参考
    返回: [(type, text, english_ref), ...]
      type: 'heading' | 'content' | 'noise'
    """
    result = []
    eng_buffer = ""  # 上一行英文，用作中文行的参考

    for p in paragraphs:
        text = p.text.strip()
        if not text:
            eng_buffer = ""
            continue

        if is_noise(text):
            continue

        if is_english_line(text):
            # 保存英文作为后续中文的参考
            eng_buffer = text
            continue

        if is_chinese_line(text):
            # 应用OCR修正
            corrected = apply_ocr_fixes(text)

            if is_heading_like(corrected):
                result.append(('heading', corrected, eng_buffer))
            else:
                result.append(('content', corrected, eng_buffer))
            eng_buffer = ""
        else:
            # 混合行（可能含中文和英文），尝试提取中文部分
            cn_chars = [c for c in text if '一' <= c <= '鿿' or '㐀' <= c <= '䶿']
            if len(cn_chars) >= 3:
                corrected = apply_ocr_fixes(text)
                result.append(('content', corrected, eng_buffer))
            eng_buffer = ""

    return result


