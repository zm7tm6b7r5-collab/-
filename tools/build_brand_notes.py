def clean_text(text: str) -> str:
    """清理文本中的噪声"""
    # 移除开头噪声
    cleaned = re.sub(r'^[\s•◆\*\-·▶ ﻿]+', '', text)
    cleaned = re.sub(r'[\s•◆\*\-·▶ ﻿]+$', '', cleaned)
    # 移除零宽字符
    cleaned = cleaned.replace('﻿', '').replace('​', '')
    # 移除多余空白
    cleaned = re.sub(r'\s+', ' ', cleaned)
    return cleaned.strip()


def is_major_heading(text: str) -> bool:
    """判断是否为一级标题（章节标题）"""
    # 数字开头且字数适中
    if re.match(r'^[一二三四五六七八九十]+[、.．）)]\s*.{2,30}$', text):
        return True
    return False


def is_minor_heading(text: str) -> bool:
    """判断是否为二级/三级标题"""
    # 带编号的子标题
    if re.match(r'^[（(][一二三四五六七八九十\d]+[）)]', text):
        return True
    if re.match(r'^\d+[、.．）)]', text):
        return True
    # 品牌+关键词的短语标题（长度适中）
    if re.match(r'^品牌.{2,15}(定义|策略|原则|步骤|构成|模型|概述|区别|联系|类型|程序|更新|塑造|保护|概念|价值)$', text):
        return True
    return False


def is_garbled(text: str) -> bool:
    """检测是否为严重乱码（不可修复的OCR错误）"""
    # 包含日文假名或韩文等非中文东亚字符
    if re.search(r'[ぁ-ゟ゠-ヿ가-힯]', text):
        return True
    # 不再用罕见字比例判断——品牌管理专业术语本身就会有很多"非常见字"
    return False


def build_document(contents: list):
    """生成结构化 Word 文档"""
    doc = Document()

    # ── 页面设置 ──
    section = doc.sections[0]
    section.page_width = Cm(21)
    section.page_height = Cm(29.7)
    section.left_margin = Cm(2.5)
    section.right_margin = Cm(2.5)

    # ── 正文样式 ──
    style = doc.styles["Normal"]
    style.font.name = "微软雅黑"
    style.font.size = Pt(11)
    style.paragraph_format.line_spacing = 1.5
    rPr = style.element.get_or_add_rPr()
    rFonts = rPr.makeelement(qn('w:rFonts'), {})
    rFonts.set(qn('w:eastAsia'), '微软雅黑')
    rPr.insert(0, rFonts)

    # ── 封面 ──
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title.paragraph_format.space_before = Pt(60)
    run = title.add_run("品牌管理课程笔记")
    run.font.size = Pt(26)
    run.font.bold = True
    run.font.name = "微软雅黑"

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run2 = subtitle.add_run("基于课堂PPT整理 · 纯中文修订版")
    run2.font.size = Pt(12)
    run2.font.color.rgb = RGBColor(128, 128, 128)

    doc.add_page_break()

    # ── 收集有效内容 ──
    cn_items = []
    for item_type, text, eng_ref in contents:
        cleaned = clean_text(text)
        if not cleaned or len(cleaned) < 2:
            continue
        # 跳过严重乱码
        if is_garbled(cleaned):
            continue
        cn_items.append((item_type, cleaned, eng_ref))

    if not cn_items:
        doc.add_paragraph("（未提取到有效中文内容）")
        doc.save(str(OUTPUT_DOCX))
        return

    # ── 状态机：组织章节结构 ──
    # 按照 major heading → content 的组织方式
    sections = []  # [(major_title, [(type, text), ...])]
    current_major = None
    current_items = []
    seen_content = set()  # 去重

    for item_type, text, eng_ref in cn_items:
        # 内容去重（相似度判断）
        text_key = text[:30] if len(text) > 30 else text
        if text_key in seen_content and len(text) < 50:
            continue
        seen_content.add(text_key)

        if is_major_heading(text):
            # 保存前一个 section
            if current_items:
                sections.append((current_major, current_items))
            current_major = text
            current_items = []
        elif item_type == 'heading' and is_minor_heading(text):
            current_items.append(('subheading', text))
        else:
            current_items.append(('text', text))

    # 最后一个 section
    if current_items:
        sections.append((current_major, current_items))

    # ── 合并重复章节标题 ──
    merged_sections = []
    seen_titles = {}
    for major, items in sections:
        title_key = major[:15] if major else ""
        if title_key and title_key in seen_titles:
            # 合并到已有章节
            idx = seen_titles[title_key]
            merged_sections[idx][1].extend(items)
        else:
            if title_key:
                seen_titles[title_key] = len(merged_sections)
            merged_sections.append([major, items])

    # ── 写入文档 ──
    heading_count = 0
    content_count = 0

    for major_title, items in merged_sections:
        if not items:
            continue

        # 写一级标题
        if major_title:
            h = doc.add_heading(major_title, level=1)
            heading_count += 1

        for item_type, text in items:
            if item_type == 'subheading':
                if len(text) <= 40:
                    doc.add_heading(text, level=2)
                    heading_count += 1
                else:
                    p = doc.add_paragraph(text)
                    content_count += 1
            else:
                # 正文 - 如果以要点符号开头，保持格式
                p = doc.add_paragraph(text)
                content_count += 1

    # ── 修订说明 ──
    doc.add_page_break()
    doc.add_heading("修订说明", level=1)
    doc.add_paragraph(
        "本笔记基于品牌管理课程 PPT 照片的手机 OCR 提取结果，"
        "经过以下步骤修订而成：\n\n"
        "1. 中英文对照：利用英文识别准确率高的特点，对照英文修正中文 OCR 错误\n"
        "2. 术语标准化：参照王新刚《品牌管理》、凯勒 CBBE 模型、艾克品牌资产五星模型等权威来源，"
        "统一专业术语表述\n"
        "3. 结构化重组：按课程知识体系组织章节，去除重复和噪音内容\n"
        "4. 纯中文输出：仅保留中文内容，适合复习使用\n\n"
        "⚠️ 由于 OCR 识别质量的固有限制，部分内容可能仍有少量错误，"
        "建议对照原 PPT 图片核对关键概念和数据。"
    )

    doc.save(str(OUTPUT_DOCX))
    print(f"[OK] 文档已保存: {OUTPUT_DOCX}")
    print(f"     共 {len(merged_sections)} 个章节, {heading_count} 个标题, {content_count} 条正文")


